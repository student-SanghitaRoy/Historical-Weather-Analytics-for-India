"""Evidence-grounded question answering over the LOADED data.

How it works
  1. parse_question() decides WHAT is asked (rule-based).
  2. This module computes the answer from the data with the same tested statistics code used by the
     dashboard. Numbers are never generated by a language model.
  3. The answer text is built from templates and re-checked with verify.unsupported_numbers().
  4. If the data cannot answer reliably, the system ABSTAINS and says why.
"""
from __future__ import annotations

import calendar
from dataclasses import asdict, dataclass, field

import pandas as pd

from weather_platform import config
from weather_platform.aggregate import SEASON_ORDER, season_bounds
from weather_platform.ai.parse import Parsed, parse_question
from weather_platform.ai.verify import unsupported_numbers
from weather_platform.stats.baseline import compare_to_baseline
from weather_platform.stats.descriptive import describe
from weather_platform.stats.rainfall import longest_dry_spell, rainfall_total, wet_dry_counts

COVERAGE_STRICT = 0.9   # totals, counts, spells, baseline comparisons need this much valid data
COVERAGE_MIN = 0.5      # below this even a mean/max is not reliable
EXAMPLES = [
    "What was the total rainfall in July 2022?",
    "What was the average temperature in 2021?",
    "What was the highest temperature in 2022?",
    "How many wet days were there in the monsoon of 2022?",
    "What was the longest dry spell in 2021?",
    "Was July 2023 unusual for rainfall compared to normal?",
    "How much data is missing for precipitation?",
]


@dataclass
class Answer:
    status: str                       # 'answered' | 'abstained'
    question: str
    text: str
    intent: str | None = None
    figures: list = field(default_factory=list)   # [{name, value, unit}]
    period_label: str = ""
    date_range: list = field(default_factory=list)
    variable: str | None = None
    source: str = ""
    chart: dict | None = None         # {'kind': 'rainfall'|'temperature', 'start', 'end', 'variable'}
    warnings: list = field(default_factory=list)
    abstain_reason: str | None = None
    verified: bool = True

    def to_dict(self) -> dict:
        return asdict(self)


# ----------------------------------------------------------------------------------------------
def _abstain(q: str, reason: str, intent=None, source="") -> Answer:
    msg = f"I can't answer this reliably from the loaded data. {reason}"
    return Answer("abstained", q, msg, intent=intent, abstain_reason=reason, source=source)


def _resolve_variable(p: Parsed, loaded: list[str]) -> tuple[str | None, list[str]]:
    notes: list[str] = []
    hint = p.variable_hint
    if hint == "precip":
        return ("precipitation_sum" if "precipitation_sum" in loaded else None), notes
    if hint == "wind":
        return ("wind_speed_10m_max" if "wind_speed_10m_max" in loaded else None), notes
    temps = [v for v in loaded if config.VARIABLES[v]["kind"] == "temperature"]
    if hint in ("temp", "temp_max", "temp_min"):
        want = {"temp": "temperature_2m_mean", "temp_max": "temperature_2m_max", "temp_min": "temperature_2m_min"}[hint]
        if want in loaded:
            return want, notes
        if temps:
            sub = "temperature_2m_mean" if "temperature_2m_mean" in temps else temps[0]
            notes.append(f"{config.VARIABLES[want]['label']} was not loaded, so {config.VARIABLES[sub]['label'].lower()} was used instead.")
            return sub, notes
    return None, notes


def _windows(p: Parsed, df: pd.DataFrame) -> tuple[list, str]:
    d0, d1 = df.index.min(), df.index.max()
    years = sorted(set(p.years))
    months = p.months
    wins: list[tuple[pd.Timestamp, pd.Timestamp]] = []
    label = ""

    def month_groups(ms):
        groups, cur = [], []
        for m in sorted(ms):
            if cur and m == cur[-1] + 1:
                cur.append(m)
            else:
                if cur:
                    groups.append(cur)
                cur = [m]
        if cur:
            groups.append(cur)
        return groups

    all_years = list(range(d0.year, d1.year + 1))
    if p.season in SEASON_ORDER:
        ys = years or list(range(d0.year, d1.year + 2))
        wins = [season_bounds(y, p.season) for y in ys]
        label = f"{p.season} {', '.join(map(str, years))}" if years else f"all {p.season} seasons"
    elif p.season == "monsoon" or months:
        ms = [6, 7, 8, 9] if p.season == "monsoon" else months
        if p.range_years:
            ys = list(range(min(years), max(years) + 1))
        else:
            ys = years or all_years
        for y in ys:
            for g in month_groups(ms):
                a = pd.Timestamp(y, g[0], 1)
                b = pd.Timestamp(y, g[-1], calendar.monthrange(y, g[-1])[1])
                wins.append((a, b))
        names = ", ".join(calendar.month_name[m] for m in ms) if p.season != "monsoon" else "monsoon (June to September)"
        if p.season == "monsoon":
            names = "the monsoon (June to September, a fixed definition used here)"
        label = names + (f" {min(years)}-{max(years)}" if p.range_years else f" {', '.join(map(str, years))}" if years else " (all years in the data)")
    elif years:
        if p.range_years:
            wins = [(pd.Timestamp(min(years), 1, 1), pd.Timestamp(max(years), 12, 31))]
            label = f"{min(years)} to {max(years)}"
        else:
            wins = [(pd.Timestamp(y, 1, 1), pd.Timestamp(y, 12, 31)) for y in years]
            label = ", ".join(map(str, years))
    else:
        wins = [(d0, d1)]
        label = f"the whole loaded period ({d0.date()} to {d1.date()})"
    wins = [(a, b) for a, b in wins if b >= d0 and a <= d1]
    return wins, label


def verification_context(ans: "Answer", baseline_years=(1991, 2020)) -> list[str]:
    """Strings whose numbers are legitimately allowed in the text (dates, labels, method constants)."""
    strs = [str(f["value"]) for f in ans.figures if isinstance(f.get("value"), str)]
    return [ans.period_label, *ans.date_range, ans.source, " ".join(ans.warnings), *strs,
            f"{baseline_years[0]} {baseline_years[1]}", "95"]  # 95 = confidence level of the stated interval


def _fmt(v, nd=1):
    return f"{v:,.{nd}f}"


def answer_question(question: str, df: pd.DataFrame, meta: dict, variables: list[str], rep=None,
                    wet_mm: float = config.WET_DAY_MM, baseline_years: tuple[int, int] = (1991, 2020),
                    city_names: list[str] | None = None, loaded_city: str | None = None) -> Answer:
    src = f"{meta.get('source', config.DATA_SOURCE['name'])} ({meta.get('location', 'location n/a')}; {meta.get('start')} to {meta.get('end')})"
    p = parse_question(question, city_names)
    q = question

    # ---------- hard abstentions (things this module must never do) ----------
    if p.flags["forecast"]:
        return _abstain(q, "This tool describes past data only; it does not make weather forecasts. "
                           "For forecasts, use an official weather service.", p.intent, src)
    if p.flags["causal"]:
        return _abstain(q, "Explaining causes needs information that is not in this dataset. I can describe what the data shows "
                           "(for example totals, averages, extremes) but not why it happened.", p.intent, src)
    if p.flags["trend"]:
        return _abstain(q, "Trend claims need a proper statistical test, so they are not answered in this chat box. "
                           "Use the 'Unusual days and trends' tab on the Location analysis page (Mann-Kendall test with Sen's slope and uncertainty).", p.intent, src)
    if p.flags["compare_locations"]:
        return _abstain(q, "Comparing locations is not available yet; only the loaded location can be queried.", p.intent, src)
    other = [c for c in p.cities if loaded_city and c.lower() != loaded_city.lower()]
    if other:
        return _abstain(q, f"The loaded data is for {loaded_city}, not {', '.join(other)}. Load that city first.", p.intent, src)
    if p.intent is None or p.variable_hint is None:
        return _abstain(q, "I could not tell which measurement and statistic you mean. Try questions like: " + " | ".join(EXAMPLES[:3]), p.intent, src)

    var, notes = _resolve_variable(p, variables)
    if var is None:
        return _abstain(q, f"The variable you asked about is not loaded. Loaded: {[config.VARIABLES[v]['label'] for v in variables]}.", p.intent, src)
    unit, label_v = config.VARIABLES[var]["unit"], config.VARIABLES[var]["label"]
    if p.intent in ("wet_days", "dry_spell", "total") and var != "precipitation_sum":
        return _abstain(q, "That statistic is only defined for precipitation.", p.intent, src)

    wins, plabel = _windows(p, df)
    if not wins:
        return _abstain(q, f"The requested period ({plabel}) is outside the loaded data ({df.index.min().date()} to {df.index.max().date()}).", p.intent, src)

    segs = [df[var].loc[a:b] for a, b in wins]
    expected = sum((b - a).days + 1 for a, b in wins)
    valid = sum(int(s.notna().sum()) for s in segs)
    coverage = valid / expected if expected else 0.0
    start = max(min(a for a, _ in wins), df.index.min())
    end = min(max(b for _, b in wins), df.index.max())
    base = dict(question=q, intent=p.intent, period_label=plabel, date_range=[str(start.date()), str(end.date())],
                variable=var, source=src, warnings=list(notes))

    strict = p.intent in ("wet_days", "dry_spell", "total", "baseline")
    if coverage < (COVERAGE_STRICT if strict else COVERAGE_MIN) and p.intent != "missing":
        return Answer("abstained", **{**base, "warnings": []},
                      text=f"I can't answer this reliably: only {coverage:.0%} of the days in {plabel} have valid {label_v.lower()} values.",
                      abstain_reason=f"coverage {coverage:.0%}")
    if coverage < COVERAGE_STRICT and p.intent != "missing":
        base["warnings"].append(f"Only {coverage:.0%} of days in this period have valid data; treat the result with caution.")

    ser = pd.concat(segs)
    chart_kind = "rainfall" if var == "precipitation_sum" else "temperature" if config.VARIABLES[var]["kind"] == "temperature" else None
    chart = {"kind": chart_kind, "start": str(start.date()), "end": str(end.date()), "variable": var} if chart_kind else None
    figs: list[dict] = []
    intent = p.intent

    if intent in ("mean", "median", "max", "min", "std"):
        d = describe(ser)
        key = {"mean": "mean", "median": "median", "max": "max", "min": "min", "std": "std"}[intent]
        val = d[key]
        if val is None:
            return _abstain(q, "Not enough valid values to compute that statistic.", intent, src)
        word = {"mean": "average", "median": "median", "max": "highest", "min": "lowest", "std": "standard deviation of"}[intent]
        figs.append({"name": f"{word} {label_v.lower()}", "value": round(val, 2), "unit": unit})
        figs += [{"name": "valid days", "value": d["n_valid"], "unit": "days"}, {"name": "missing days", "value": d["n_missing"], "unit": "days"}]
        text = f"For {plabel}, the {word} {label_v.lower()} was {_fmt(val)} {unit}"
        if intent in ("max", "min"):
            when = d["max_date"] if intent == "max" else d["min_date"]
            text += f", on {when}"
            figs.append({"name": "date", "value": when, "unit": ""})
        text += f" (based on {d['n_valid']} valid days"
        text += f", {d['n_missing']} missing)." if d["n_missing"] else ")."
        if intent == "mean" and var == "precipitation_sum":
            text += " This is the mean daily value, including dry days."
    elif intent == "total":
        t = rainfall_total(ser)
        figs += [{"name": "total precipitation", "value": round(t["total_mm"], 1), "unit": "mm"},
                 {"name": "valid days", "value": t["n_valid_days"], "unit": "days"},
                 {"name": "missing days", "value": t["n_missing_days"], "unit": "days"}]
        text = f"The total precipitation for {plabel} was {_fmt(t['total_mm'])} mm over {t['n_valid_days']} valid days."
        if t["is_lower_bound"]:
            text += f" {t['n_missing_days']} day(s) are missing, so this is a lower bound."
    elif intent == "wet_days":
        c = wet_dry_counts(ser, wet_mm)
        figs += [{"name": "wet days", "value": c["wet_days"], "unit": "days"},
                 {"name": "threshold", "value": wet_mm, "unit": "mm"},
                 {"name": "valid days", "value": c["wet_days"] + c["dry_days"], "unit": "days"}]
        text = (f"There were {c['wet_days']} wet days (at least {wet_mm} mm) out of {c['wet_days'] + c['dry_days']} valid days in {plabel}. "
                f"{c['zero_rain_days']} days had exactly zero rainfall.")
        figs += [{"name": "zero-rain days", "value": c["zero_rain_days"], "unit": "days"},
                 {"name": "missing days", "value": c["missing_days"], "unit": "days"}]
        if c["missing_days"]:
            text += f" {c['missing_days']} day(s) are missing and were not counted."
    elif intent == "dry_spell":
        best = max((longest_dry_spell(s, wet_mm) for s in segs), key=lambda x: x["length_days"])
        if best["length_days"] == 0:
            text = f"There was no dry spell (a run of days under {wet_mm} mm) in {plabel}."
            figs.append({"name": "longest dry spell", "value": 0, "unit": "days"})
        else:
            figs += [{"name": "longest dry spell", "value": best["length_days"], "unit": "days"},
                     {"name": "start", "value": best["start"], "unit": ""}, {"name": "end", "value": best["end"], "unit": ""},
                     {"name": "threshold", "value": wet_mm, "unit": "mm"}]
            text = (f"The longest dry spell in {plabel} lasted {best['length_days']} days, from {best['start']} to {best['end']} "
                    f"(days under {wet_mm} mm; a missing day ends a spell).")
    elif intent == "missing":
        miss = expected - valid
        pct = 100 * miss / expected
        figs += [{"name": "missing days", "value": miss, "unit": "days"}, {"name": "expected days", "value": expected, "unit": "days"},
                 {"name": "missing", "value": round(pct, 2), "unit": "%"}]
        text = f"For {label_v.lower()} in {plabel}, {miss} of {expected} days ({pct:.1f}%) have no valid value."
        if var == "precipitation_sum":
            z = int((ser == 0).sum())
            figs.append({"name": "zero-rain days", "value": z, "unit": "days"})
            text += f" This is separate from the {z} days with a real measurement of zero rainfall."
        chart = None
    elif intent == "baseline":
        if len(wins) != 1:
            return _abstain(q, "Baseline comparison needs one specific period (for example 'July 2023' or '2022').", intent, src)
        stat = "sum" if var == "precipitation_sum" else "mean"
        r = compare_to_baseline(df[var], wins[0][0], wins[0][1], baseline_years, stat=stat, relative=(stat == "sum"))
        if r["status"] != "ok":
            return _abstain(q, f"{r['reason']} Load data covering the baseline years {baseline_years[0]}-{baseline_years[1]}.", intent, src)
        if "z_score" not in r:
            return _abstain(q, "Please ask about a single year's window for baseline comparisons.", intent, src)
        lo, hi = r["difference_interval"]
        word = "total" if stat == "sum" else "average"
        figs += [{"name": f"{word} in period", "value": round(r["selected_mean"], 2), "unit": unit if stat == "mean" else "mm"},
                 {"name": "baseline mean", "value": round(r["baseline_mean"], 2), "unit": unit if stat == "mean" else "mm"},
                 {"name": "difference", "value": round(r["difference"], 2), "unit": unit if stat == "mean" else "mm"},
                 {"name": "z-score", "value": round(r["z_score"], 2), "unit": ""},
                 {"name": "percentile in baseline", "value": round(r["percentile_in_baseline"], 0), "unit": "%"},
                 {"name": "interval low", "value": round(lo, 2), "unit": ""}, {"name": "interval high", "value": round(hi, 2), "unit": ""},
                 {"name": "baseline years", "value": r["n_baseline_years"], "unit": "years"}]
        u = unit if stat == "mean" else "mm"
        verdict = "outside" if r["outside_normal_variability"] else "within"
        text = (f"For {plabel}, the {word} {label_v.lower()} was {_fmt(r['selected_mean'], 2)} {u}, compared with a baseline mean of "
                f"{_fmt(r['baseline_mean'], 2)} {u} ({r['n_baseline_years']} years, {baseline_years[0]}-{baseline_years[1]}). "
                f"The difference is {r['difference']:+.2f} {u} (z = {r['z_score']:.2f}; this period ranks at about the "
                f"{r['percentile_in_baseline']:.0f}th percentile of baseline years). Normal year-to-year variability gives a 95% range of "
                f"{lo:+.2f} to {hi:+.2f}, so the difference is {verdict} that range.")
        base["warnings"] += ["Assumes roughly independent, normally distributed baseline years; rainfall totals are skewed."]
        if r["n_baseline_years"] < 20:
            base["warnings"].append(f"Short baseline ({r['n_baseline_years']} years); climatological baselines normally use about 30.")
    else:
        return _abstain(q, "That question type is not supported.", intent, src)

    # reanalysis caveat on every answer
    base["warnings"].append("Based on ERA5 reanalysis (gridded model data), which can differ from station observations.")

    ans = Answer("answered", text=text, figures=figs, chart=chart, **base)
    bad = unsupported_numbers(ans.text, ans.figures, verification_context(ans, baseline_years))
    if bad:  # defensive: should never happen for template output
        return Answer("abstained", **{**base, "warnings": []},
                      text="I could not verify my own numbers for this answer, so I am not showing it.",
                      abstain_reason=f"unverified numbers {bad}")
    return ans
